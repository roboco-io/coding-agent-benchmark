"""analysis/latency/runs.csv → dashboard/index.html의 LAT 상수(/* LAT:BEGIN */ … /* LAT:END */)를 갱신한다.
LAT[행 이름] = [[exp, 모델대기s, 도구s, 모델호출수, 호출당대기s, 모델대기1초당output, 모델대기비중], ...] (runs.csv 순서 = 대시보드 run 순서)"""
import csv, json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
lat = {}
for r in csv.DictReader(open(os.path.join(ROOT, 'analysis/latency/runs.csv'))):
    lat.setdefault(r['row'], []).append([r['exp'], int(r['model_s']), int(r['tool_s']), int(r['model_calls']),
        float(r['s_per_call']), float(r['out_per_model_s']), float(r['model_share'])])
js = '/* LAT:BEGIN — generated by analysis/latency/build_dashboard_data.py (EN runs only; [exp, model wait s, tool s, model calls, s per call, output per model-wait s, model-wait share]) */\nconst LAT = ' + json.dumps(lat, ensure_ascii=False, separators=(',', ':')) + ';\n/* LAT:END */'
p = os.path.join(ROOT, 'dashboard/index.html'); s = open(p).read()
if '/* LAT:BEGIN' in s: s = re.sub(r'/\* LAT:BEGIN.*?/\* LAT:END \*/', lambda m: js, s, flags=re.S)
else: s = s.replace('/* card order + swatch stack */', js + '\n\n/* card order + swatch stack */', 1)
open(p, 'w').write(s)
